import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const chaptersDirectory = join(repositoryRoot, "docs/manual/chapters");
const indexPath = join(repositoryRoot, "docs/manual/index.json");
const generatedPath = join(repositoryRoot, "panel/src/app/docs/chapters.generated.ts");

const files = (await readdir(chaptersDirectory)).filter((file) => file.endsWith(".md")).sort();
const chapters = await Promise.all(files.map(async (file) => parseChapter(file, await readFile(join(chaptersDirectory, file), "utf8"))));
chapters.sort((left, right) => left.order - right.order);

const index = chapters.map(({ content, story, ...chapter }) => ({
  ...chapter,
  headings: [...content.matchAll(/^##\s+(.+)$/gm)].map((match) => match[1]),
  excerpt: normalize(content).slice(0, 180),
  search_text: normalize(`${content}\n${story}`),
}));

await mkdir(dirname(indexPath), { recursive: true });
await writeFile(indexPath, `${JSON.stringify({ version: 1, chapters: index }, null, 2)}\n`);
await mkdir(dirname(generatedPath), { recursive: true });
await writeFile(generatedPath, `// Generated by scripts/build-doc-index.mjs. Do not edit.\nexport const chapters = ${JSON.stringify(chapters, null, 2)} as const;\n`);

console.log(`generated ${chapters.length} Markdown chapters, search index, and reader data`);

function parseChapter(file, source) {
  const match = source.match(/^---\n(?<frontmatter>[\s\S]*?)\n---\n(?<body>[\s\S]*)$/);
  if (!match?.groups) throw new Error(`Invalid frontmatter: ${file}`);

  const fields = parseFrontmatter(match.groups.frontmatter);
  const [content, story = ""] = match.groups.body.split("<!-- story -->", 2).map((part) => part.trim());
  const order = Number(fields.order);
  if (!fields.id || !fields.title || !fields.estimate || !Number.isInteger(order)) {
    throw new Error(`Missing id, title, order, or estimate: ${file}`);
  }

  return {
    id: fields.id,
    label: fields.title,
    order,
    estimate: fields.estimate,
    keywords: fields.keywords,
    path: relative(repositoryRoot, join(chaptersDirectory, file)),
    content,
    story,
  };
}

function parseFrontmatter(frontmatter) {
  const fields = { keywords: [] };
  let currentKey = "";
  for (const line of frontmatter.split("\n")) {
    if (line.startsWith("  - ")) {
      if (currentKey === "keywords") fields.keywords.push(line.slice(4).trim());
      continue;
    }
    const separator = line.indexOf(":");
    if (separator < 0) continue;
    currentKey = line.slice(0, separator).trim();
    const value = line.slice(separator + 1).trim();
    if (currentKey !== "keywords") fields[currentKey] = value;
  }
  return fields;
}

function normalize(value) {
  return value
    .replace(/<!--[^]*?-->/g, " ")
    .replace(/[`*_#[\]()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}
